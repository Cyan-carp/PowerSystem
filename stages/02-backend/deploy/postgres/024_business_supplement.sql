CREATE TABLE IF NOT EXISTS field_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id bigint NOT NULL REFERENCES devices(id),
  -- Preserve the original ID if an authorized historical alarm reset removes the row.
  alarm_id bigint,
  actor_id bigint NOT NULL REFERENCES users(id),
  request_id uuid NOT NULL,
  symptoms text NOT NULL,
  measures text NOT NULL,
  result text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (actor_id, request_id)
);
CREATE INDEX IF NOT EXISTS field_records_device_id_idx ON field_records(device_id, id DESC);
CREATE INDEX IF NOT EXISTS field_records_alarm_id_idx ON field_records(alarm_id, id DESC) WHERE alarm_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS prediction_feedback (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prediction_id bigint NOT NULL REFERENCES prediction_records(id),
  actor_id bigint NOT NULL REFERENCES users(id),
  request_id uuid NOT NULL,
  status text NOT NULL CHECK (status IN ('confirmed_fault', 'not_occurred', 'watching')),
  occurred_at timestamptz,
  note text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (actor_id, request_id),
  CHECK ((status = 'confirmed_fault') = (occurred_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS prediction_feedback_prediction_id_idx ON prediction_feedback(prediction_id, id DESC);
