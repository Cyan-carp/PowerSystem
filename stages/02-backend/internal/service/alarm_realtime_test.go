func alarmRepairDB(t *testing.T) *gorm.DB {
	t.Helper()
	dsn := os.Getenv("ALARM_REPAIR_TEST_DSN")
	if dsn == "" {
		t.Skip("requires a dedicated alarm_repair_20261030_* database")
	}
	db, err := gorm.Open(postgres.Open(dsn), &gorm.Config{Logger: logger.Default.LogMode(logger.Silent)})
	if err != nil {
		t.Fatal("isolated database unavailable")
	}
	pool, _ := db.DB()
	t.Cleanup(func() { pool.Close() })
	var name string
	if db.Raw("SELECT current_database()").Scan(&name).Error != nil || !strings.HasPrefix(name, "alarm_repair_20261030_") {
		t.Fatal("dedicated fixture database required")
	}
	for _, path := range store.MigrationPaths {
		if err := store.Migrate(db, filepath.Join("../..", path)); err != nil {
			t.Fatal(err)
		}
	}
	return db
}

func TestSafeDailyWindowsThroughIngressAndRules(t *testing.T) {
	db := alarmRepairDB(t)
	catalog, err := fleet.Load("testdata/safe-window-fleet.json")
	if err != nil {
		t.Fatal(err)
	}
	identities, err := SimulationCatalogIdentities(catalog)
	if err != nil {
		t.Fatal(err)
	}
	for _, identity := range identities {
		d := model.Device{DeviceCode: identity.DeviceCode, StationCode: identity.StationCode, Name: identity.DeviceCode, DevType: "inverter", IsSimulated: true}
		if err := db.Clauses(clause.OnConflict{Columns: []clause.Column{{Name: "device_code"}}, DoNothing: true}).Create(&d).Error; err != nil {
			t.Fatal(err)
		}
	}
	report, err := EnsureSimulationPolicyDevices(db, catalog)
	if err != nil || !report.OK {
		t.Fatalf("fixture policy: %+v %v", report, err)
	}
	if err := store.Migrate(db, "../../deploy/postgres/012_natural_alarm_rules.sql"); err != nil {
		t.Fatal(err)
	}
	var cases []struct {
		Metric           string
		Trigger, Recover json.RawMessage
	}
	data, err := os.ReadFile("testdata/safe-window-samples.json")
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(data, &cases); err != nil {
		t.Fatal(err)
	}
	if len(cases) != 10 {
		t.Fatal("two complete five-slot days required")
	}
	for _, c := range cases {
		for index, raw := range []json.RawMessage{c.Trigger, c.Recover} {
			// Use the actual production ingress validator on Python-generated bytes.
			sample, err := telemetry.ParseStored(raw)
			if err != nil {
				t.Fatal(err)
			}
			clock := time.UnixMilli(sample.TS).UTC()
			var device model.Device
			if err := db.Where("device_code=?", sample.DeviceCode).First(&device).Error; err != nil {
				t.Fatal(err)
			}
			item := model.Inbox{DeviceID: device.ID, RunID: sample.RunID, Seq: sample.Seq, TS: sample.TS, Payload: raw, ReceivedAt: clock, TDConfirmedAt: &clock}
			if err := db.Create(&item).Error; err != nil {
				t.Fatal(err)
			}
			for attempt := 0; attempt < 2; attempt++ {
				var events []AlarmEvent
				err := TelemetryTransaction(db, func(tx *gorm.DB) error {
					if err := TelemetryDeviceLock(tx, device.ID); err != nil {
						return err
					}
					var current model.Inbox
					if err := tx.Clauses(clause.Locking{Strength: "UPDATE"}).First(&current, item.ID).Error; err != nil {
						return err
					}
					var e error
					events, e = processLockedSample(tx, current, sample, device, false, clock)
					return e
				})
				if err != nil {
					t.Fatal(err)
				}
				if attempt == 1 {
					if len(events) != 0 {
						t.Fatal("duplicate alarm/recovery on retry")
					}
					continue
				}
				want := "alarm_created"
				if index == 1 {
					want = "alarm_recovered"
				}
				if len(events) != 1 || events[0].Type != want || events[0].Data.Metric != c.Metric || events[0].Data.Origin != "normal" {
					t.Fatalf("%s %s: %+v", device.DeviceCode, want, events)
				}
			}
			var retained model.Inbox
			db.First(&retained, item.ID)
			if retained.ProcessedAt != nil || retained.BusinessState == nil || *retained.BusinessState != "pending" || retained.AlarmEvaluation == nil || *retained.AlarmEvaluation != "evaluated" {
				t.Fatal("realtime evaluation rewrote historical receipt")
			}
		}
	}
	var count int64
	db.Raw("SELECT count(*) FROM alarm_records WHERE (triggered_at AT TIME ZONE 'Asia/Shanghai')::date IN ('2026-10-30','2026-10-31')").Scan(&count)
	if count != 10 {
		t.Fatal("expected exactly five natural alarms on each fixed day", count)
	}
	t.Log("all ten real simulator windows pass Go ingress, trigger ordinary rules once, recover once, retain pending receipts and rotate the next day")
}
