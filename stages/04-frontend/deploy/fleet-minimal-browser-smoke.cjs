// One local browser, three views, seven fixture devices; recorded Go responses.
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright-core')

async function main() {
  const responseFile = process.argv[2]
  if (!responseFile) throw new Error('Pass the api-responses.json generated by TestFleetMinimalSmoke')
  const recorded = JSON.parse(fs.readFileSync(responseFile, 'utf8'))
  const output = path.dirname(responseFile)
  const base = 'http://127.0.0.1:5178'
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  const results = []
  const errors = []
  let scope = 'business'
  let history = []
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    await context.addInitScript(() => {
      sessionStorage.setItem('powersystem_token', 'offline-smoke-placeholder')
      sessionStorage.setItem('powersystem_user', JSON.stringify({ id: 1, username: 'smoke', real_name: '本地冒烟', role: 'operator' }))
    })
    await context.route('**/*', async route => {
      const url = new URL(route.request().url())
      if (url.origin !== base) return route.abort()
      if (!url.pathname.startsWith('/api/')) return route.continue()
      const endpoint = url.pathname.replace('/api/v1/', '')
      const requested = url.searchParams.get('scope') || 'all'
      let envelope = recorded[`${endpoint}?scope=${requested}`]
      if (envelope) {
        envelope = structuredClone(envelope)
        if (endpoint === 'devices' && url.searchParams.has('station_code')) {
          envelope.data.list = envelope.data.list.filter(d => d.station_code === url.searchParams.get('station_code'))
          envelope.data.total = envelope.data.list.length
        }
        return route.fulfill({ json: envelope })
      }
      if (/devices\/\d+\/telemetry$/.test(endpoint)) {
        history.push({ scope, endpoint })
        return route.fulfill({ json: { code: 0, message: 'success', data: { device_id: Number(endpoint.split('/')[1]), metric: 'power', points: [] } } })
      }
      if (endpoint === 'ws-ticket') return route.fulfill({ status: 503, json: { code: 50300, message: 'offline smoke', data: null } })
      if (endpoint === 'agent/interpretations') return route.fulfill({ json: { code: 0, message: 'success', data: { list: [], total: 0, page: 1, page_size: 100 } } })
      errors.push(`Unexpected local API request: ${endpoint}`)
      return route.fulfill({ status: 503, json: { code: 50300, message: 'unrecorded offline endpoint', data: null } })
    })
    const page = await context.newPage()
    page.on('pageerror', e => errors.push(e.message))
    for (const [route, title] of [['dashboard', '运行总览'], ['devices', '设备管理'], ['alarms', '告警中心']]) {
      scope = 'business'
      await page.goto(`${base}/${route}`, { waitUntil: 'domcontentloaded', timeout: 60000 })
      await page.getByRole('heading', { name: title, exact: true }).waitFor({ timeout: 30000 })
      for (const [value, label, count] of [['business', '业务范围', 4], ['all', '全平台', 7], ['baseline', '基线演示', 3]]) {
        scope = value
        const target = page.waitForResponse(r => r.url().includes(`/api/v1/${route === 'dashboard' ? 'dashboard/overview' : route}?`) && r.url().includes(`scope=${value}`), { timeout: 15000 })
        if (value === 'business') await page.getByRole('button', { name: '刷新', exact: true }).count().then(async n => {
          if (n) await page.getByRole('button', { name: '刷新', exact: true }).click()
          else await page.reload({ waitUntil: 'domcontentloaded' })
        })
        else await page.getByRole('button', { name: label, exact: true }).click()
        await target
        await page.waitForFunction(() => !document.querySelector('.el-loading-mask'), null, { timeout: 15000 })
        const body = await page.locator('body').innerText()
        if (route === 'dashboard' && !body.includes(`期望 ${count} 台`)) throw new Error(`${route}/${value} count missing`)
        if (route === 'devices' && !body.includes(`共 ${count} 台设备`)) throw new Error(`${route}/${value} count missing`)
        if (route === 'alarms' && !body.includes('暂无')) throw new Error('alarm empty state missing')
        results.push({ route, scope: value, passed: true })
      }
      if (route === 'dashboard') await page.screenshot({ path: path.join(output, 'baseline-dashboard.png'), fullPage: true })
    }
    scope = 'business'
    await page.goto(`${base}/devices`, { waitUntil: 'domcontentloaded' })
    await page.getByText('共 4 台设备', { exact: true }).waitFor()
    await page.locator('.el-select__wrapper').first().click()
    await page.getByRole('option').filter({ hasText: 'PV-04' }).click()
    await page.getByText('共 2 台设备', { exact: true }).waitFor()
    results.push({ route: 'devices', station: 'PV-04', passed: true })
    await page.screenshot({ path: path.join(output, 'devices-pv04.png'), fullPage: true })
    if (errors.length) throw new Error(errors.join('; '))
    if (history.some(h => h.scope !== 'baseline')) throw new Error('business/all requested per-device history')
    const report = { passed: true, mode: 'local-browser-recorded-go-responses', checks: results, page_errors: errors, history_requests: history.length, history_scopes: [...new Set(history.map(h => h.scope))] }
    fs.writeFileSync(path.join(output, 'browser-summary.json'), JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report))
    await context.close()
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
