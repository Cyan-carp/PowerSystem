const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const yaml = require('js-yaml');
const root = path.resolve(__dirname, '..');
const run = path.resolve(root, '../../artifacts/v5-desktop/s02-20261026-r1');
const config = yaml.load(fs.readFileSync(path.join(root, 'electron-builder.yml'), 'utf8'));
config.appId = 'cn.cyancarp.powersystem.desktop.s02test';
config.productName = '源网智联 S02 隔离验收';
config.directories.app = path.join(run, 'isolated-app');
config.directories.output = path.join(run, 'isolated-package');
config.win.executableName = 'PowerSystem S02 Test';
config.nsis.shortcutName = config.productName;
config.nsis.uninstallDisplayName = config.productName;
config.nsis.artifactName = 'PowerSystem-S02-Isolated-${version}-${arch}-Setup.${ext}';
config.extraResources = [{ from: path.join(root, 'src/fallback.html'), to: 'fallback.html' }];
config.npmRebuild = false;
const file = path.join(run, 'isolated-builder.json');
fs.writeFileSync(file, JSON.stringify(config, null, 2));
const result = spawnSync(process.execPath, [path.join(root, 'node_modules/electron-builder/cli.js'), '--config', file, '--win', 'nsis', '--x64', '--publish', 'never'], { cwd: root, stdio: 'inherit', env: process.env });
process.exit(result.status ?? 1);
