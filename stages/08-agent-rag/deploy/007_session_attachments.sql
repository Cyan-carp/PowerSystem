CREATE TABLE IF NOT EXISTS rag_attachments (
  id uuid PRIMARY KEY,
  user_id bigint NOT NULL CHECK (user_id > 0),
  session_id uuid REFERENCES rag_sessions(id) ON DELETE CASCADE,
  name text NOT NULL,
  size_bytes integer NOT NULL,
  excerpts jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS rag_attachments_owner_drafts ON rag_attachments(user_id, created_at) WHERE session_id IS NULL;
CREATE INDEX IF NOT EXISTS rag_attachments_session ON rag_attachments(session_id) WHERE session_id IS NOT NULL;

-- Separate storage prevents the normal model/history path from fetching local-only content.
CREATE TABLE IF NOT EXISTS rag_attachment_turns (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id uuid NOT NULL REFERENCES rag_sessions(id) ON DELETE CASCADE,
  user_id bigint NOT NULL,
  request_id uuid NOT NULL,
  request_session_id uuid,
  attachment_ids uuid[] NOT NULL,
  question text NOT NULL,
  excerpts jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_id, request_id)
);
CREATE INDEX IF NOT EXISTS rag_attachment_turns_session ON rag_attachment_turns(session_id,id);

CREATE OR REPLACE FUNCTION rag_cleanup_deleted_session_attachments() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
    DELETE FROM rag_attachment_turns WHERE session_id=NEW.id;
    DELETE FROM rag_attachments WHERE session_id=NEW.id;
  END IF;
  RETURN NEW;
END;
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='rag_sessions'::regclass AND tgname='rag_deleted_session_cleanup') THEN
    CREATE TRIGGER rag_deleted_session_cleanup AFTER UPDATE OF deleted_at ON rag_sessions
    FOR EACH ROW EXECUTE FUNCTION rag_cleanup_deleted_session_attachments();
  END IF;
END;
$$;
