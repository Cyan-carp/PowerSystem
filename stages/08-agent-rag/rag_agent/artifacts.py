MAX_BYTES = 32 << 20
GENERATION_SECONDS = 60
MIMES = {'csv':'text/csv; charset=utf-8', 'xlsx':'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'}


class ReportArgs(Args):
    kind: Literal['availability','alarm-timeliness','energy','telemetry','investigation']
    start: str | None = None
    end: str | None = None
    start_date: str | None = None
    end_date: str | None = None
    station_code: str | None = Field(default=None, pattern=r'^[A-Za-z0-9_-]{1,64}$')
    device_id: int | None = Field(default=None, gt=0)
    scope: Literal['all','business','baseline'] = 'all'
    group_by: Literal['station','device'] = 'station'
    deliver: bool = True

    @model_validator(mode='after')
    def window(self):
        if self.kind == 'energy':
            if not self.start_date or not self.end_date or self.start or self.end:
                raise ValueError('energy requires start_date/end_date only')
            first = datetime.strptime(self.start_date, '%Y-%m-%d')
            last = datetime.strptime(self.end_date, '%Y-%m-%d')
        else:
            if not self.start or not self.end or self.start_date or self.end_date:
                raise ValueError('requires explicit timezone start/end only')
            first, last = (datetime.fromisoformat(x.replace('Z','+00:00')) for x in (self.start,self.end))
            if first.tzinfo is None or last.tzinfo is None: raise ValueError('timezone required')
        days = (last-first).total_seconds()/86400
        if days <= 0 or days > (7 if self.kind == 'telemetry' else 31): raise ValueError('window exceeds limit')
        if self.kind == 'telemetry' and not self.device_id: raise ValueError('telemetry requires device_id')
        # The two legacy reports never supported fleet scope. Do not silently
        # accept an ignored filter or fan out to independently timed snapshots.
        if self.kind in ('availability','alarm-timeliness','telemetry') and self.scope != 'all':
            raise ValueError('legacy report uses station_code/device_id; scope must be all')
        if self.kind == 'telemetry' and self.station_code: raise ValueError('telemetry uses device_id only')
        return self


SCHEMA = {'type':'function','function':{'name':'business_report',
    'description':'直接读取权威业务报表并交付本人CSV与XLSX（同一份快照转换，文件正文不进模型）。kind=availability设备可用率、alarm-timeliness平台告警时效、energy发电量按站/设备、telemetry单设备遥测、investigation告警调查清单。日期与时区必须明确：energy start_date/end_date为北京时间自然日，结束不含，最多31天；其余start/end为带时区时间，最多31天（遥测7天20万行）。旧可用率/时效仅station_code/device_id交集筛选，scope必须all。deliver=false只查询并返回元数据。缺值不补造，不代表故障诊断或维修时长，无新审批或写执行。',
    'parameters':ReportArgs.model_json_schema()}}


def metadata(row):
    return {k:str(row[k]) if k in ('artifact_id','run_id','created_at','expires_at') else row[k]
            for k in ('artifact_id','run_id','name','mime_type','size','sha256','created_at','expires_at','status')}


class ArtifactService:
    def __init__(self, runs, cfg, client):
        self.runs, self.pool, self.cfg, self.client = runs, runs.pool, cfg, client
        self.root = Path(cfg.artifact_dir).resolve()

    def path(self, key):
        # All storage names are UUIDs generated by this module.
        if str(UUID(key)) != key: raise ValueError('invalid storage key')
        result = (self.root/key).resolve()
        if result.parent != self.root: raise ValueError('invalid storage key')
        return result

    async def fetch(self, path, params, jwt):
        async with self.client.stream('GET', self.cfg.backend_url+path, params=params,
                headers={'Authorization':'Bearer '+jwt}, timeout=45) as reply:
            if reply.status_code != 200: raise ValueError('backend_http_'+str(reply.status_code))
            data = bytearray()
            async for part in reply.aiter_bytes():
                data.extend(part)
                if len(data) > MAX_BYTES: raise ValueError('artifact_size_limit')
            return bytes(data), dict(reply.headers)

    async def collect(self, args, jwt):
        params = args.model_dump(exclude_none=True, exclude={'kind','deliver','scope','group_by'})
        if args.kind == 'energy': params.update(scope=args.scope,group_by=args.group_by)
        if args.kind == 'telemetry': params.pop('device_id',None)
        path = '/api/v1/devices/'+str(args.device_id)+'/telemetry/export' if args.kind=='telemetry' else '/api/v1/reports/'+args.kind
        if args.kind == 'investigation': return await self.investigation(args,jwt)
        params['format'] = 'csv'
        raw, headers = await self.fetch(path,params,jwt)
        if not headers.get('content-type','').startswith('text/csv'): raise ValueError('backend_not_csv')
        # Parse only to count and expose column names. Values remain in the file.
        reader = csv.reader(io.StringIO(raw.decode('utf-8-sig')),strict=True)
        columns = next(reader,None)
        if not columns: raise ValueError('empty_backend_csv')
        energy_columns=['记录类型','分组','场站编码','设备ID','日期','发电量(kWh)','完整','缺口原因']
        if args.kind=='energy' and columns[:8]!=energy_columns: raise ValueError('energy_csv_schema_changed')
        count = 0; energy=[]; missing=0
        for values in reader:
            if len(values)!=len(columns): raise ValueError('backend_csv_schema_changed')
            count+=1
            if args.kind=='energy':
                if values[0] in ('total','group_total') and len(energy)<100:
                    energy.append(dict(record_type=values[0],station_code=values[2],device_id=values[3],kwh=values[5] or None,complete=values[6]))
                if values[0]=='missing': missing+=1
        return raw, dict(source=path,query=params,timezone='Asia/Shanghai',end_exclusive=args.kind!='telemetry',
            rule_version=headers.get('x-rule-version','telemetry-export-v1'),computed_at=headers.get('x-computed-at'),
            complete=headers.get('x-data-complete','unknown'),rows=count,columns=columns,
            **(dict(energy_summary=dict(groups=energy,missing_device_days=missing,summary_truncated=len(energy)>=100)) if args.kind=='energy' else {}),
            note='空值和数据不足保留在文件；可用率不等于在线率，告警时效不等于维修时长。遥测沿用既有[start,end]口径。')

    async def investigation(self,args,jwt):
        path='/api/v1/alarms'
        params={k:v for k,v in args.model_dump(exclude_none=True).items() if k in ('start','end','station_code','device_id','scope')}
        # Query a complete bounded set; detect page drift/duplicates. A changing
        # live set fails explicitly rather than inventing a consistent snapshot.
        records=[]; total=None; seen=set(); stamps=[]
        for page in range(1,21):
            raw,_=await self.fetch(path,{**params,'page':page,'page_size':100},jwt)
            envelope=json.loads(raw)
            if envelope.get('code')!=0: raise ValueError('backend_report_failed')
            data=envelope['data']
            if total is None: total=data['total']
            if data['total']!=total or total>2000: raise ValueError('investigation_limit_or_changed')
            for row in data['list']:
                if row['id'] in seen: raise ValueError('investigation_changed')
                seen.add(row['id']);records.append(row)
            stamps.append(datetime.now(timezone.utc).isoformat())
            if len(records)>=total: break
        if len(records)!=total: raise ValueError('investigation_incomplete')
        # Recheck the set to detect ordinary concurrent paging changes. This is
        # an observed query interval, not a claimed database transaction snapshot.
        check,_=await self.fetch(path,{**params,'page':1,'page_size':100},jwt)
        check=json.loads(check)['data']
        if check['total']!=total or [r['id'] for r in check['list']]!=[r['id'] for r in records[:100]]: raise ValueError('investigation_changed')
        stamp=datetime.now(timezone.utc).isoformat();query=urlencode(params)
        out=io.StringIO(newline='');writer=csv.writer(out)
        writer.writerow(['告警ID','设备ID','级别','状态','触发时间','确认时间','恢复时间','待调查事项','数据缺口','来源','查询条件','区间开始(含)','区间结束(含)','时区','生成时间'])
        def safe(value):
            text='' if value is None else str(value)
            return "'"+text if text.startswith(('=','+','-','@','\t','\r')) else text
        for row in records:
            gaps=[key for key in ('triggered_at','acked_at','recovered_at') if not row.get(key)]
            writer.writerow([safe(x) for x in (row['id'],row.get('device_id'),row.get('level'),row.get('status'),row.get('triggered_at'),row.get('acked_at'),row.get('recovered_at'),
                '核对事件原因与现场记录；未确认/未恢复不推断为维修失败',','.join(gaps),path+'/'+str(row['id']),query,args.start,args.end,'Asia/Shanghai',stamp)])
        raw=out.getvalue().encode('utf-8-sig')
        return raw,dict(source=path,query=params,timezone='Asia/Shanghai',end_exclusive=False,computed_at=stamp,rows=total,complete=True,
            observed_start=stamps[0],observed_end=stamp,consistency='bounded paged observation; not a transactional snapshot',
            note='空集保留表头；确认/恢复空值为待核实或未完成，不补零、不推断故障已修复。')

    async def create(self,runtime,call_id,args,jwt):
        hashed=digest(args.model_dump())
        old=await self.pool.fetchrow('SELECT * FROM assistant_artifact_batches WHERE run_id=$1 AND call_id=$2',runtime.row['id'],call_id)
        if old:
            if old['request_hash']!=hashed: raise ValueError('artifact_request_changed')
            summary=json.loads(old['summary'])
            if old['status']=='failed': raise ValueError(summary['error'])
            return summary
        started=time.monotonic()
        written=[]
        try:
            async with asyncio.timeout(GENERATION_SECONDS):
                await runtime.check()
                raw,provenance=await self.collect(args,jwt)
                if len(raw)>MAX_BYTES: raise ValueError('artifact_size_limit')
                if not args.deliver: return dict(report=provenance,artifacts=[])
                xlsx=await asyncio.to_thread(render_csv_xlsx,raw)
                if len(xlsx)>MAX_BYTES: raise ValueError('artifact_size_limit')
                await runtime.check()
                self.root.mkdir(parents=True, exist_ok=True)
                artifacts=[]
                for extension,content in (('csv',raw),('xlsx',xlsx)):
                    aid=uuid5(runtime.row['id'],'artifact:'+call_id+':'+extension)
                    storage_key=str(uuid4())
                    target=self.path(storage_key)
                    # A completed, unjournaled batch is reused above. Here files
                    # are unpublished until the DB transaction and events commit.
                    temp=target.with_suffix('.'+str(runtime.worker)+'.tmp')
                    temp.write_bytes(content);os.replace(temp,target);written.append(target)
                    artifacts.append(dict(id=aid,storage_key=storage_key,name=args.kind+'.'+extension,mime_type=MIMES[extension],size=len(content),sha256=hashlib.sha256(content).hexdigest()))
                provenance.update(generation_seconds=round(time.monotonic()-started,4),csv_snapshot_sha256=hashlib.sha256(raw).hexdigest(),limits=dict(bytes=MAX_BYTES,seconds=GENERATION_SECONDS))
                async with self.pool.acquire() as c,c.transaction():
                    row=await self.runs.locked(c,runtime.row['id'],runtime.worker,runtime.row['lease_epoch'])
                    if row['cancel_requested'] or row['deadline']<=datetime.now(timezone.utc): raise ValueError('artifact_cancelled_or_expired_run')
                    if hasattr(runtime,'authorize_delivery'):await runtime.authorize_delivery(c)
                    public=[]
                    for item in artifacts:
                        saved=await c.fetchrow('''INSERT INTO assistant_artifacts(id,run_id,user_id,call_id,name,mime_type,storage_key,size,sha256,status,provenance)
                          VALUES($1,$2,$3,$4,$5,$6,$7,$8,$9,'ready',$10::jsonb) RETURNING *,id AS artifact_id''',item['id'],row['id'],row['user_id'],call_id,item['name'],item['mime_type'],item['storage_key'],item['size'],item['sha256'],encode(provenance))
                        public.append(metadata(saved))
                    row['artifacts'] += public
                    for item in public: await self.runs._event(c,row,'artifact_ready',item)
                    summary=dict(report=provenance,artifacts=public)
                    await c.execute("INSERT INTO assistant_artifact_batches(run_id,call_id,request_hash,status,summary) VALUES($1,$2,$3,'ready',$4::jsonb)",row['id'],call_id,hashed,encode(summary))
                return summary
        except BaseException as error:
            # Per-attempt random storage keys avoid deleting a newer worker's
            # winner when an old lease fails after writing unpublished files.
            for target in written:
                try:
                    registered=await self.pool.fetchval('SELECT EXISTS(SELECT 1 FROM assistant_artifacts WHERE storage_key=$1)',target.name)
                    if not registered: target.unlink(missing_ok=True)
                except OSError: pass
            await self.pool.execute('INSERT INTO assistant_artifact_attempts(run_id,call_id,outcome) VALUES($1,$2,$3)',runtime.row['id'],call_id,type(error).__name__)
            if isinstance(error,(asyncio.CancelledError,LostLease)): raise
            # Keep failed metadata and a stable error; never manufacture a link.
            code=str(error) if isinstance(error,ValueError) else 'artifact_generation_failed'
            async with self.pool.acquire() as c,c.transaction():
                row=await self.runs.locked(c,runtime.row['id'],runtime.worker,runtime.row['lease_epoch'])
                await c.execute("INSERT INTO assistant_artifact_batches(run_id,call_id,request_hash,status,summary) VALUES($1,$2,$3,'failed',$4::jsonb) ON CONFLICT DO NOTHING",row['id'],call_id,hashed,encode(dict(error=code)))
            raise ValueError(code) from None

    async def audit(self,aid,user,outcome,byte_count=0):
        await self.pool.execute('INSERT INTO assistant_artifact_downloads(artifact_id,user_id,outcome,run_id,byte_count) VALUES($1,$2,$3,(SELECT run_id FROM assistant_artifacts WHERE id=$1),$4)',aid,user,outcome,byte_count)

    async def set_status(self,aid,state):
        async with self.pool.acquire() as c,c.transaction():
            artifact=await c.fetchrow('SELECT * FROM assistant_artifacts WHERE id=$1 FOR UPDATE',aid)
            if not artifact or artifact['status']==state:return
            await c.execute('UPDATE assistant_artifacts SET status=$2 WHERE id=$1',aid,state)
            row=unpack(await c.fetchrow('SELECT * FROM assistant_runs WHERE id=$1 FOR UPDATE',artifact['run_id']))
            row['artifacts']=[{**a,'status':state} if a.get('artifact_id')==str(aid) else a for a in row['artifacts']]
            # Projection and its event remain one committed prefix, including
            # metadata changes after the original task has finished.
            await self.runs._event(c,row,'progress',dict(phase=row['phase'],message='产物状态已更新：'+state))

    async def get(self,aid,user,download=False):
        row=await self.pool.fetchrow('SELECT *,id AS artifact_id FROM assistant_artifacts WHERE id=$1 AND user_id=$2',aid,user)
        if not row:
            if download: await self.audit(aid,user,'not_found_or_not_owner')
            raise HTTPException(404,'artifact_not_found')
        state=row['status']
        if row['expires_at']<=datetime.now(timezone.utc): state='expired'
        if state!='ready':
            if state!=row['status']: await self.set_status(aid,state)
            if download: await self.audit(aid,user,state)
            if not download: return {**metadata(row),'status':state}
            raise HTTPException(410,'artifact_'+state)
        try:
            with self.path(row['storage_key']).open('rb') as stream: content=stream.read(MAX_BYTES+1)
            if len(content)!=row['size'] or hashlib.sha256(content).hexdigest()!=row['sha256']: raise ValueError()
        except (OSError,ValueError):
            await self.set_status(aid,'unavailable')
            if download: await self.audit(aid,user,'integrity_failed')
            if not download: return {**metadata(row),'status':'unavailable'}
            raise HTTPException(410,'artifact_unavailable') from None
        if download:
            # Audit failure aborts the download. This authorizes serving bytes;
            # it cannot claim that the browser saved a completed local file.
            await self.audit(aid,user,'authorized_delivery')
            return metadata(row),content
        return {**metadata(row),'provenance':json.loads(row['provenance'])}

    async def expire(self):
        rows=await self.pool.fetch("SELECT id FROM assistant_artifacts WHERE expires_at<=now() AND status<>'expired' ORDER BY expires_at LIMIT 200")
        for row in rows:
            await self.set_status(row['id'],'expired')
        # Retry file cleanup for an earlier failed unlink without deleting metadata.
        for row in await self.pool.fetch("SELECT id,storage_key FROM assistant_artifacts WHERE status='expired' AND file_removed_at IS NULL ORDER BY expires_at LIMIT 200"):
            try:
                self.path(row['storage_key']).unlink(missing_ok=True)
                await self.pool.execute('UPDATE assistant_artifacts SET file_removed_at=now() WHERE id=$1',row['id'])
            except OSError: pass
        if self.root.exists():
            # Bounded recovery of unpublished crash leftovers. Only our UUID
            # storage names, older than the 60-second generation budget + grace.
            for target in islice(self.root.iterdir(),200):
                try:
                    parts=target.name.split('.')
                    if len(parts) not in (1,3) or len(parts)==3 and parts[-1]!='tmp':continue
                    if str(UUID(parts[0]))!=parts[0]:continue
                    if len(parts)==3: UUID(parts[1])
                    if target.stat().st_mtime>time.time()-3600:continue
                    registered=await self.pool.fetchval('SELECT EXISTS(SELECT 1 FROM assistant_artifacts WHERE storage_key=$1)',parts[0])
                    if not registered: target.unlink(missing_ok=True)
                except (OSError,ValueError):pass


class ReportTools:
    def __init__(self,base,service,runtime):
        self.base,self.service,self.runtime=base,service,runtime
        self.schemas=[*base.schemas,SCHEMA]
        self.call_id=None

    def __getattr__(self,name): return getattr(self.base,name)

    async def execute(self,name,arguments,jwt,result):
        if name!='business_report': return await self.base.execute(name,arguments,jwt,result)
        trace=dict(name=name,arguments={},status='error',collected_at=datetime.now(timezone.utc).isoformat())
        result['tool_calls'].append(trace)
        try:
            args=ReportArgs.model_validate_json(arguments)
            trace['arguments']=args.model_dump(exclude_none=True)
            value=await self.service.create(self.runtime,self.call_id,args,jwt)
            trace.update(status='ok',result=value)
            result.setdefault('artifacts',[]).extend(x for x in value['artifacts'] if x not in result.get('artifacts',[]))
            result.setdefault('reports',[]).append(value['report'])
            result['sources'].append(dict(id='report-'+str(len(result['reports'])),kind='business',title=args.kind,url=value['report']['source'],collected_at=trace['collected_at']))
            return value
        except Exception as error:
            reason=str(error) if isinstance(error,ValueError) and not hasattr(error,'errors') else 'report_parameters_or_dependency_failed'
            trace['error']=reason;result['warnings'].append(reason)
            return dict(error=reason)
